#ifndef SUNXI_MMAP_H
#define SUNXI_MMAP_H

/* Memory regions */
#define SUNXI_ROM_BASE			0x00000000 // FIXS_BROM (0x0000 0000---0x0000 BFFF)
#define SUNXI_ROM_SIZE			0x00015000 // HS_BROM (0x0001 0000---0x0001 4FFF)
#define SUNXI_SRAM_BASE			0x01000000 // SH_SRAM??? (0x0100 0000---0x0107 FFFF)
#define SUNXI_SRAM_SIZE			0x00080000 // 512KB
#define SUNXI_SRAM_A1_BASE		0x01000000 // use SH_SRAM?
#define SUNXI_SRAM_A1_SIZE		0x00020000 // size ????
#define SUNXI_SRAM_A2_BASE		0x00040000 // SRAM A2 (0x0004 0000---0x0006 BFFF)
#define SUNXI_SRAM_A2_BL31_OFFSET	0x00014000 // SRAM A2 first 16KB(4000) only for AR100
#define SUNXI_SRAM_A2_SIZE		0x0002C000
#define SUNXI_DEV_BASE			0x01000000
#define SUNXI_DEV_SIZE			0x09000000
#define SUNXI_DRAM_BASE			0x40000000
#define SUNXI_DRAM_VIRT_BASE		0x0a000000

/* Memory-mapped devices */
#define SUNXI_CCU_BASE			0x02000000
#define SUNXI_SPC_BASE			0x02006000
#define SUNXI_WDOG_BASE			0x02050000
#define SUNXI_UART0_BASE		0x02600000
#define SUNXI_SYSCON_BASE		0x03000000
#define SUNXI_DMA_BASE			0x03001000
#define SUNXI_SID_BASE			0x03006000
#define SUNXI_GICD_BASE			0x03400000
#define SUNXI_GICC_BASE			0x03460000
#define SUNXI_PIO_BASE			0x03604000
#define SUNXI_SPI0_BASE			0x04025000
#define SUNXI_R_SPC_BASE		0x07002000
#define SUNXI_R_TZMA_BASE		0x07003000
#define SUNXI_R_PRCM_BASE		0x07010000
#define SUNXI_R_WDOG_BASE		0x07021000
#define SUNXI_R_CPUCFG_BASE		0x07032000
#define SUNXI_R_PIO_BASE		0x07096000
#define SUNXI_R_UART_BASE		0x07080000
#define SUNXI_R_I2C_BASE		0x07083000
#define SUNXI_MSGBOX_BASE		0x07094000
// #define SUNXI_DSP_PRCM_BASE		0x07102000 NO MCU_PRCM in T536
#define SUNXI_CPUCFG_BASE		0x08000000
#define SUNXI_C0_CPUXCFG_BASE		0x09800000

#endif /* SUNXI_MMAP_H */
